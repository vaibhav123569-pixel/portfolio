import {readFile,access} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=await readFile('dist/index.html','utf8');
const css=await readFile('dist/styles.css','utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length,'Duplicate IDs');
for(const m of html.matchAll(/href="#([^"]+)"/g))assert(ids.includes(m[1]),'Broken section anchor: '+m[1]);
for(const m of html.matchAll(/(?:src|href)="([^"#:]+\.(?:css|js|png))"/g))await access('dist/'+m[1]);
for(const m of css.matchAll(/url\('([^']+)'\)/g))await access('dist/'+m[1]);
const context={window:{}};vm.runInNewContext(await readFile('dist/profile.js','utf8'),context);
const p=context.window.portfolioProfile;
assert.equal(p.email,'vaibhav123569@gmail.com');
assert.equal(new URL(p.linkedin).hostname,'www.linkedin.com');
assert.equal(new URL(p.github).pathname,'/vaibhav123569-pixel');
for(const m of html.matchAll(/data-project="([^"]+)"/g))assert(p.projects[m[1]],'Missing project details');
assert.match(html,/type="email"/);assert.match(html,/prefers-reduced-motion|styles.css/);
assert.match(css,/prefers-reduced-motion/);assert.match(css,/@media\(max-width:680px\)/);
console.log('PASS: section anchors, unique IDs, local assets, verified profile links, project associations, and responsive/reduced-motion rules.');
console.log('Browser layout and interactive behavior require separate manual review.');
